from talker.engineering_plan import circle_requirements, source_checked_circle_plan


SOURCE = '''[Source 1: independent MSOP.pdf, page 40]
Part | MSOP: FAI 31 (SPC S) 53.26 +0.12/-0.12
Measured System    ALI_ALT
Dimension System    ALI_ALT
Measure 1 vision circle CIR_TEST_7.
Dimension Y Value
Program    UP
[Source 2: independent MSOP.pdf, page 15]
Part | MSOP: ALI_ALT
Use DATUMB_LIN and DATUMD_LIN to construct a intersection point NEW_ORIGIN.
Set NEW_ORIGIN as Y Zero.
Program    UP
Coordinate unit label: X, Y, Z (mm)
'''


def test_source_plan_uses_current_feature_and_final_origin_not_project_constants():
    requirements = circle_requirements('FAI 31 出具光学方案和BOM', SOURCE)
    assert requirements['nominal'] == '53.26'
    assert requirements['origin'] == 'NEW_ORIGIN'
    plan = source_checked_circle_plan('FAI 31 出具光学方案和BOM', SOURCE)
    assert '53.26' in plan and 'CIR_TEST_7' in plan and 'NEW_ORIGIN' in plan
    assert '62.58' not in plan and 'BD_ORIGN' not in plan
    assert '8.1699' in plan and '0.4223' in plan
    assert '平行于孔口面的法向' in plan
    assert '计量平台' in plan and '接触测头或3D' in plan
    assert '假设' in plan and '尚未完成' in plan


def test_missing_conflicting_or_wrong_scope_source_cannot_create_authoritative_plan():
    assert circle_requirements('FAI 23 方案', SOURCE) is None
    assert circle_requirements('FAI 31 方案', SOURCE.replace('Program    UP', 'Program    DOWN', 1)) is None
    assert circle_requirements('FAI 31 方案', SOURCE.replace('Set NEW_ORIGIN as Y Zero.', 'Origin not specified.')) is None
    conflict = SOURCE + '\n[Source 3: independent MSOP.pdf, page 16]\nMSOP: ALI_ALT\nSet OTHER_ORIGIN as Y Zero.\nProgram    UP'
    assert circle_requirements('FAI 31 方案', conflict) is None
    assert source_checked_circle_plan('FAI 31 只输出JSON', SOURCE) is None
    assert source_checked_circle_plan('FAI 31 方案，FOV=40 mm', SOURCE) is None


def test_design_route_uses_source_checked_plan_without_llm_guessing(tmp_path, monkeypatch):
    from talker.model import TalkerModel
    model = TalkerModel(tmp_path)
    model.model = object()
    model.processor = object()

    class Retriever:
        def curated_context(self, *args, **kwargs):
            return None
        def context(self, *args, **kwargs):
            return SOURCE

    model.retriever = Retriever()
    def forbid_generation(*args, **kwargs):
        raise AssertionError('Source facts and arithmetic must not be regenerated by the LLM')
    monkeypatch.setattr(model, '_answer_with_auto_continue', forbid_generation)
    answer = model.answer([{'role':'user','content':'FAI31出具光学方案和BOM'}])
    assert '53.26' in answer and '8.1699' in answer
